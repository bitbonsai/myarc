#!/usr/bin/env python3
"""Writes a header holding a file's bytes as a constexpr array.

  embed_bytes.py <input> <output.h> <name>
"""

import sys


def main():
    source, output, name = sys.argv[1:]
    data = open(source, 'rb').read()
    guard = 'MYARC_' + name.upper() + '_H_'
    rows = [
        '    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ','
        for i in range(0, len(data), 16)
    ]
    with open(output, 'w') as f:
        f.write(f'// Generated by myarc/embed_bytes.py from {source}. Do not edit.\n')
        f.write(f'#ifndef {guard}\n#define {guard}\n\n#include <cstdint>\n\n')
        f.write('namespace myarc {\n\n// clang-format off\n')
        f.write(f'inline constexpr uint8_t k{name}[] = {{\n')
        f.write('\n'.join(rows))
        f.write('\n};\n// clang-format on\n\n}  // namespace myarc\n\n')
        f.write(f'#endif  // {guard}\n')


if __name__ == '__main__':
    main()
